import SwiftUI
import AtlasCore

// Domain area labels — peel de AtlasWorkspace+AreaLabel.

extension AtlasArea {
    var labelDomain: String? {
        switch self {
        case .operacional: return "Operacional"
        case .autonomos: return "Autônomos"
        case .programacao: return "Programação"
        default: return nil
        }
    }
}
